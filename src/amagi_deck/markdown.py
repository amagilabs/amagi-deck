"""Render a Deck as one markdown file."""

from __future__ import annotations

from typing import List, Optional

from . import __version__
from .model import Chart, Deck, Slide, Table


def fmt_num(v: Optional[float]) -> str:
    if v is None:
        return ""
    if float(v).is_integer() and abs(v) < 1e15:
        return str(int(v))
    return "%.10g" % v


def cell(text: str) -> str:
    return text.replace("\\", "\\\\").replace("|", "\\|").replace("\n", "<br>") if text else ""


def md_table(rows: List[List[str]]) -> List[str]:
    if not rows:
        return []
    width = max(len(r) for r in rows)
    rows = [r + [""] * (width - len(r)) for r in rows]
    out = ["| " + " | ".join(cell(c) for c in rows[0]) + " |",
           "|" + "---|" * width]
    for r in rows[1:]:
        out.append("| " + " | ".join(cell(c) for c in r) + " |")
    return out


def chart_rows(chart: Chart) -> List[List[str]]:
    if not chart.series:
        return []
    scatter = any(s.x_values for s in chart.series)
    if scatter:
        rows = [["Series", "X", "Y"]]
        for s in chart.series:
            for x, y in zip(s.x_values, s.values):
                rows.append([s.name, fmt_num(x), fmt_num(y)])
        return rows
    n = max(len(s.values) for s in chart.series)
    cats = list(chart.categories) + [""] * max(0, n - len(chart.categories))
    rows = [["Category"] + [s.name for s in chart.series]]
    for i in range(n):
        label = cats[i] or str(i + 1)
        rows.append([label] + [fmt_num(s.values[i]) if i < len(s.values) else "" for s in chart.series])
    return rows


def slide_md(slide: Slide, include_notes: bool = True) -> List[str]:
    title = slide.title or "(untitled)"
    head = "## Slide %d: %s" % (slide.number, title)
    if slide.hidden:
        head += " (hidden)"
    lines = [head, ""]
    if slide.image:
        lines += ["![Slide %d](%s)" % (slide.number, slide.image.replace(" ", "%20")), ""]
    text_lines = []
    for block in slide.text:
        for level, text in block.lines:
            text_lines.append("  " * int(level or 0) + "- " + text)
    if text_lines:
        lines += text_lines + [""]
    for i, table in enumerate(slide.tables, start=1):
        label = "**Table %d**" % i if len(slide.tables) > 1 else "**Table**"
        lines += [label, ""] + md_table(table.rows) + [""]
    for chart in slide.charts:
        label = "**Chart: %s** (%s)" % (chart.title, chart.kind) if chart.title else "**Chart** (%s)" % chart.kind
        rows = chart_rows(chart)
        lines += [label, ""]
        lines += (md_table(rows) if rows else ["(no data cached in the file)"]) + [""]
    if slide.pictures:
        pics = []
        for p in slide.pictures:
            item = "- %s" % p.name
            if p.alt_text:
                item += ': "%s"' % p.alt_text
            else:
                item += " (no alt text)"
            pics.append(item)
        lines += ["**Pictures**", ""] + pics + [""]
    if slide.links:
        lines += ["**Links**", ""] + ["- %s" % u for u in slide.links] + [""]
    if include_notes and slide.notes:
        lines += ["**Speaker notes**", ""] + ["> " + ln if ln else ">" for ln in slide.notes.splitlines()] + [""]
    return lines


def deck_md(deck: Deck, include_notes: bool = True) -> str:
    title = deck.title or deck.source
    size = ""
    if deck.width_in and deck.height_in:
        size = ", %g x %g in" % (deck.width_in, deck.height_in)
    counts = [
        "%d slides" % len(deck.slides),
        "%d hidden" % sum(1 for s in deck.slides if s.hidden),
        "%d with notes" % sum(1 for s in deck.slides if s.notes),
        "%d charts" % sum(len(s.charts) for s in deck.slides),
        "%d tables" % sum(len(s.tables) for s in deck.slides),
    ]
    lines = [
        "# %s" % title,
        "",
        "Source: `%s` (%s%s). Slide images: %s. %s." % (
            deck.source, deck.kind, size, deck.renderer or "none", ", ".join(counts)),
        "",
        "<!-- generated by amagi-deck %s -->" % __version__,
        "",
    ]
    for w in deck.warnings:
        lines.append("> Note: %s" % w)
    if deck.warnings:
        lines.append("")
    lines += ["## Outline", ""]
    for s in deck.slides:
        lines.append("%d. %s%s" % (s.number, s.title or "(untitled)", " (hidden)" if s.hidden else ""))
    lines.append("")
    for s in deck.slides:
        lines += slide_md(s, include_notes)
    return "\n".join(lines).rstrip() + "\n"
